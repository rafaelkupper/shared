#!/bin/sh
# Records the current skills/ tree as a reviewed snapshot (skills.lock).
# Run it after reviewing skill changes, then commit skills/ and skills.lock together.
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)
out="$here/skills.lock"
{
  echo "# Generated by scripts/snapshot.sh. Do not edit by hand."
  echo "skills:"
  for d in "$here"/skills/*/; do
    [ -f "$d/SKILL.md" ] || continue
    name=$(basename "$d")
    echo "  - name: $name"
    echo "    sha256: $("$here/scripts/tree-hash.sh" "$d")"
  done
} > "$out"
echo "wrote $out"
